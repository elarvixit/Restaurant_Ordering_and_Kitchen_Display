-- Restaurant Ordering & Kitchen Display: database for Supabase.
--
-- Run once in Supabase: Dashboard -> SQL Editor -> New query -> paste this whole file -> Run.
-- It is safe to run again: nothing is dropped, and the menu and tables are only added when empty.
--
-- Every table and index starts with babji_RestaurantKitchen_ so this app can share a Supabase
-- project with other apps. The names are in double quotes so Postgres keeps the capital letters;
-- when you query them yourself, quote them too, e.g.  SELECT * FROM "babji_RestaurantKitchen_orders";
--
-- Money is in rupees with 2 decimals (NUMERIC(10,2), e.g. 480.00). Timestamps are milliseconds since 1970 (BIGINT).
-- Must match src/schema.js (the app creates the same tables itself if they are missing).

BEGIN;

-- ---------------------------------------------------------------- tables

CREATE TABLE IF NOT EXISTS "babji_RestaurantKitchen_menu_categories" (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        TEXT    NOT NULL,
  sort_order  INTEGER NOT NULL DEFAULT 0,
  archived_at BIGINT
);

CREATE TABLE IF NOT EXISTS "babji_RestaurantKitchen_menu_items" (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id  INTEGER NOT NULL REFERENCES "babji_RestaurantKitchen_menu_categories"(id),
  name         TEXT    NOT NULL,
  price        NUMERIC(10, 2) NOT NULL CHECK (price >= 0),  -- rupees, e.g. 480.00
  is_veg       INTEGER NOT NULL DEFAULT 1 CHECK (is_veg IN (0, 1)),
  prep_minutes INTEGER NOT NULL DEFAULT 10 CHECK (prep_minutes >= 0),
  is_available INTEGER NOT NULL DEFAULT 1 CHECK (is_available IN (0, 1)),
  emoji        TEXT    NOT NULL DEFAULT '',  -- the dish's mini picture on the menu
  photo        TEXT    NOT NULL DEFAULT '',  -- photo file in public/img/menu/, '' = show the emoji
  archived_at  BIGINT                        -- items are archived, never deleted
);

CREATE TABLE IF NOT EXISTS "babji_RestaurantKitchen_tables" (
  id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number INTEGER NOT NULL UNIQUE,
  seats  INTEGER NOT NULL DEFAULT 4
);

CREATE TABLE IF NOT EXISTS "babji_RestaurantKitchen_bills" (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_id       INTEGER NOT NULL REFERENCES "babji_RestaurantKitchen_tables"(id),
  subtotal       NUMERIC(12, 2) NOT NULL,  -- rupees, before GST
  gst            NUMERIC(12, 2) NOT NULL,
  total          NUMERIC(12, 2) NOT NULL,
  closed_at      BIGINT  NOT NULL
);

-- A table is "occupied" while it has orders with paid_at IS NULL.
CREATE TABLE IF NOT EXISTS "babji_RestaurantKitchen_orders" (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_id     INTEGER NOT NULL REFERENCES "babji_RestaurantKitchen_tables"(id),
  status       TEXT    NOT NULL DEFAULT 'New'
               CHECK (status IN ('New', 'Preparing', 'Ready', 'Served')),
  placed_at    BIGINT  NOT NULL,
  preparing_at BIGINT,
  ready_at     BIGINT,
  served_at    BIGINT,
  paid_at      BIGINT,
  bill_id      INTEGER REFERENCES "babji_RestaurantKitchen_bills"(id)
);

-- item_name and unit_price_at_order are snapshots taken when the line is added,
-- so later menu edits never change a placed order.
CREATE TABLE IF NOT EXISTS "babji_RestaurantKitchen_order_items" (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id            INTEGER NOT NULL REFERENCES "babji_RestaurantKitchen_orders"(id) ON DELETE CASCADE,
  item_id             INTEGER NOT NULL REFERENCES "babji_RestaurantKitchen_menu_items"(id),
  item_name           TEXT    NOT NULL,
  qty                 INTEGER NOT NULL CHECK (qty > 0),
  note                TEXT    NOT NULL DEFAULT '',
  unit_price_at_order NUMERIC(10, 2) NOT NULL CHECK (unit_price_at_order >= 0),  -- rupees
  added_at            BIGINT  NOT NULL
);

-- 'version' is the live-sync change counter; 'schema' is the schema version the app checks.
CREATE TABLE IF NOT EXISTS "babji_RestaurantKitchen_app_state" (
  name TEXT PRIMARY KEY,
  num  BIGINT NOT NULL
);

-- Wrong-PIN counter per client address (locked for a minute after 5 tries).
CREATE TABLE IF NOT EXISTS "babji_RestaurantKitchen_login_failures" (
  ip       TEXT PRIMARY KEY,
  failures INTEGER NOT NULL,
  until_at BIGINT  NOT NULL
);

-- ---------------------------------------------------------------- indexes

CREATE INDEX IF NOT EXISTS "babji_RestaurantKitchen_idx_orders_open"
  ON "babji_RestaurantKitchen_orders"(table_id) WHERE paid_at IS NULL;
CREATE INDEX IF NOT EXISTS "babji_RestaurantKitchen_idx_orders_active"
  ON "babji_RestaurantKitchen_orders"(status, placed_at) WHERE status <> 'Served';
CREATE INDEX IF NOT EXISTS "babji_RestaurantKitchen_idx_orders_placed"
  ON "babji_RestaurantKitchen_orders"(placed_at);
CREATE INDEX IF NOT EXISTS "babji_RestaurantKitchen_idx_orders_ready"
  ON "babji_RestaurantKitchen_orders"(ready_at);
CREATE INDEX IF NOT EXISTS "babji_RestaurantKitchen_idx_order_items_ord"
  ON "babji_RestaurantKitchen_order_items"(order_id);
CREATE INDEX IF NOT EXISTS "babji_RestaurantKitchen_idx_order_items_item"
  ON "babji_RestaurantKitchen_order_items"(item_id);
CREATE INDEX IF NOT EXISTS "babji_RestaurantKitchen_idx_bills_closed"
  ON "babji_RestaurantKitchen_bills"(closed_at);
CREATE INDEX IF NOT EXISTS "babji_RestaurantKitchen_idx_items_category"
  ON "babji_RestaurantKitchen_menu_items"(category_id);

-- ---------------------------------------------------------------- paise -> rupees
-- Databases created before this change stored money as whole paise (48000) in *_paise columns.
-- This converts them in place to rupees (480.00). It does nothing on a database that is already
-- in rupees, so it is safe to run again. (The app does the same conversion on its own at start.)

DO $$
DECLARE
  c RECORD;
BEGIN
  FOR c IN SELECT * FROM (VALUES
      ('babji_RestaurantKitchen_menu_items',  'price_paise',         'price',               10),
      ('babji_RestaurantKitchen_order_items', 'unit_price_at_order', 'unit_price_at_order', 10),
      ('babji_RestaurantKitchen_bills',       'subtotal_paise',      'subtotal',            12),
      ('babji_RestaurantKitchen_bills',       'gst_paise',           'gst',                 12),
      ('babji_RestaurantKitchen_bills',       'total_paise',         'total',               12)
    ) AS m(tbl, old_col, new_col, prec)
  LOOP
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = current_schema() AND table_name = c.tbl
                 AND column_name = c.old_col AND data_type = 'integer') THEN
      IF c.old_col <> c.new_col THEN
        EXECUTE format('ALTER TABLE %I RENAME COLUMN %I TO %I', c.tbl, c.old_col, c.new_col);
      END IF;
      EXECUTE format('ALTER TABLE %I ALTER COLUMN %I TYPE NUMERIC(%s, 2) USING %I / 100.0',
                     c.tbl, c.new_col, c.prec, c.new_col);
    END IF;
  END LOOP;
END $$;

