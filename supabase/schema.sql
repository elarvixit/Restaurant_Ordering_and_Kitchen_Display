-- ---------------------------------------------------------------- security
-- Supabase exposes every table in "public" through its REST API to anyone holding the project's
-- anon key. Row level security with no policies blocks that completely. The app itself connects
-- with the database connection string (as the table owner), which row level security does not limit.

ALTER TABLE "babji_RestaurantKitchen_menu_categories" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "babji_RestaurantKitchen_menu_items"      ENABLE ROW LEVEL SECURITY;
ALTER TABLE "babji_RestaurantKitchen_tables"          ENABLE ROW LEVEL SECURITY;
ALTER TABLE "babji_RestaurantKitchen_bills"           ENABLE ROW LEVEL SECURITY;
ALTER TABLE "babji_RestaurantKitchen_orders"          ENABLE ROW LEVEL SECURITY;
ALTER TABLE "babji_RestaurantKitchen_order_items"     ENABLE ROW LEVEL SECURITY;
ALTER TABLE "babji_RestaurantKitchen_app_state"       ENABLE ROW LEVEL SECURITY;
ALTER TABLE "babji_RestaurantKitchen_login_failures"  ENABLE ROW LEVEL SECURITY;

