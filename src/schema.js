const SEED_EMOJI = new Map(SEED_MENU.flatMap(([, items]) => items.map((i) => [i[0], i[4]])));

// Creates tables, upgrades older databases in place, and seeds an empty one.
// Safe to run on every start. On Postgres an advisory lock stops two cold-starting
// serverless instances from seeding twice.
const SCHEMA_VERSION = 2; // bump when upgrade() learns something new

async function setup(db) {
  // Fast path for serverless cold starts: one query when the database is current.
  try {
    const rows = await db.query(`SELECT num FROM ${T.app_state} WHERE name = 'schema'`);
    if (rows[0] && Number(rows[0].num) >= SCHEMA_VERSION) return;
  } catch { /* app_state not created yet */ }

  if (db.dialect === 'postgres') {
    await db.tx(async (t) => {
      await t.query('SELECT pg_advisory_xact_lock(7201)');
      for (const stmt of ddl('postgres').split(';').map((s) => s.trim()).filter(Boolean)) await t.query(stmt);
      await upgrade(t);
      await seed(t);
    });
  } else {
    await db.exec(ddl('sqlite'));
    await db.tx(async (t) => { await upgrade(t); await seed(t); });
  }
}

async function upgrade(t) {
  const cols = (await t.query(t.dialect === 'postgres'
    ? 'SELECT column_name AS name FROM information_schema.columns WHERE table_name = $1'
    : 'SELECT name FROM pragma_table_info($1)', ['menu_items'])).map((c) => c.name);
  if (!cols.includes('emoji')) {
    await t.query("ALTER TABLE menu_items ADD COLUMN emoji TEXT NOT NULL DEFAULT ''");
    for (const [name, emoji] of SEED_EMOJI) {
      await t.query(`UPDATE ${T.menu_items} SET emoji = $1 WHERE name = $2 AND emoji = ''`, [emoji, name]);
    }
  }
  await t.query(`INSERT INTO ${T.app_state} (name, num) VALUES ('version', $1) ON CONFLICT (name) DO NOTHING`, [Date.now()]);
  await t.query(`INSERT INTO ${T.app_state} (name, num) VALUES ('schema', $1)
                 ON CONFLICT (name) DO UPDATE SET num = excluded.num`, [SCHEMA_VERSION]);
}

async function seed(t) {
  const [{ n }] = await t.query(`SELECT COUNT(*) AS n FROM ${T.menu_categories}`);
  if (Number(n) > 0) return;
  for (const [i, [category, items]] of SEED_MENU.entries()) {
    const [{ id: catId }] = await t.query(
      `INSERT INTO ${T.menu_categories} (name, sort_order) VALUES ($1, $2) RETURNING id`, [category, i + 1]);
    for (const [name, rupees, veg, prep, emoji] of items) {
      await t.query(`INSERT INTO ${T.menu_items} (category_id, name, price_paise, is_veg, prep_minutes, emoji)
                     VALUES ($1, $2, $3, $4, $5, $6)`, [catId, name, rupees * 100, veg, prep, emoji]);
    }
  }
  for (let n = 1; n <= 12; n++) {
    await t.query(`INSERT INTO ${T.tables} (number, seats) VALUES ($1, $2)`, [n, n <= 8 ? 4 : 6]);
  }
}

module.exports = { setup, SEED_MENU };
