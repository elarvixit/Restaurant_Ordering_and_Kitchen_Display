'use strict';
// Schema, upgrades and seed data, shared by SQLite and Postgres.
// Money is integer paise; timestamps are integer milliseconds since the epoch.

const ddl = (dialect) => {
  const ID = dialect === 'postgres' ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY';
  const TS = dialect === 'postgres' ? 'BIGINT' : 'INTEGER';
  return `
CREATE TABLE IF NOT EXISTS ${T.menu_categories} (
  id          ${ID},
  name        TEXT    NOT NULL,
  sort_order  INTEGER NOT NULL DEFAULT 0,
  archived_at ${TS}
);

CREATE TABLE IF NOT EXISTS ${T.menu_items} (
  id           ${ID},
  category_id  INTEGER NOT NULL REFERENCES ${T.menu_categories}(id),
  name         TEXT    NOT NULL,
  price_paise  INTEGER NOT NULL CHECK (price_paise >= 0),
  is_veg       INTEGER NOT NULL DEFAULT 1 CHECK (is_veg IN (0, 1)),
  prep_minutes INTEGER NOT NULL DEFAULT 10 CHECK (prep_minutes >= 0),
  is_available INTEGER NOT NULL DEFAULT 1 CHECK (is_available IN (0, 1)),
  emoji        TEXT    NOT NULL DEFAULT '',  -- the dish's mini picture on the menu
  -- Items are archived, never deleted, so historical order_items keep a valid FK.
  archived_at  ${TS}
);

CREATE TABLE IF NOT EXISTS ${T.tables} (
  id     ${ID},
  number INTEGER NOT NULL UNIQUE,
  seats  INTEGER NOT NULL DEFAULT 4
);

CREATE TABLE IF NOT EXISTS ${T.bills} (
  id             ${ID},
  table_id       INTEGER NOT NULL REFERENCES ${T.tables}(id),
  subtotal_paise INTEGER NOT NULL,
  gst_paise      INTEGER NOT NULL,
  total_paise    INTEGER NOT NULL,
  closed_at      ${TS} NOT NULL
);

-- A table is "occupied" while it has orders with paid_at IS NULL.
-- There is deliberately no separate occupied flag that could drift out of sync.
CREATE TABLE IF NOT EXISTS ${T.orders} (
  id           ${ID},
  table_id     INTEGER NOT NULL REFERENCES ${T.tables}(id),
  status       TEXT    NOT NULL DEFAULT 'New'
               CHECK (status IN ('New', 'Preparing', 'Ready', 'Served')),
  placed_at    ${TS} NOT NULL,
  preparing_at ${TS},
  ready_at     ${TS},
  served_at    ${TS},
  paid_at      ${TS},
  bill_id      INTEGER REFERENCES ${T.bills}(id)
);

-- item_name and unit_price_at_order are snapshots taken when the line is added.
-- Later menu edits (price change, rename, marked unavailable) never touch them.
CREATE TABLE IF NOT EXISTS ${T.order_items} (
  id                  ${ID},
  order_id            INTEGER NOT NULL REFERENCES ${T.orders}(id) ON DELETE CASCADE,
  item_id             INTEGER NOT NULL REFERENCES ${T.menu_items}(id),
  item_name           TEXT    NOT NULL,
  qty                 INTEGER NOT NULL CHECK (qty > 0),
  note                TEXT    NOT NULL DEFAULT '',
  unit_price_at_order INTEGER NOT NULL CHECK (unit_price_at_order >= 0),
  added_at            ${TS} NOT NULL
);

-- Change counter for live sync: every write bumps it, screens refetch when it moves.
CREATE TABLE IF NOT EXISTS ${T.app_state} (
  name TEXT PRIMARY KEY,
  num  ${TS} NOT NULL
);

-- Wrong-PIN counter per client address (lockout after 5 tries), shared by all servers.
CREATE TABLE IF NOT EXISTS ${T.login_failures} (
  ip       TEXT PRIMARY KEY,
  failures INTEGER NOT NULL,
  until_at ${TS} NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_orders_open      ON orders(table_id) WHERE paid_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_orders_active    ON orders(status, placed_at) WHERE status <> 'Served';
CREATE INDEX IF NOT EXISTS idx_orders_placed    ON orders(placed_at);
CREATE INDEX IF NOT EXISTS idx_orders_ready     ON orders(ready_at);
CREATE INDEX IF NOT EXISTS idx_order_items_ord  ON order_items(order_id);
CREATE INDEX IF NOT EXISTS idx_order_items_item ON order_items(item_id);
CREATE INDEX IF NOT EXISTS idx_bills_closed     ON bills(closed_at);
CREATE INDEX IF NOT EXISTS idx_items_category   ON menu_items(category_id);
`;
};

